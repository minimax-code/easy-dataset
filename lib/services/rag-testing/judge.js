/**
 * LLM Judge service for RAG evaluation.
 * Scores faithfulness (answer groundedness in context) and relevancy (answer-question alignment).
 */

export class RAGJudge {
  constructor(llmClient) {
    this.llmClient = llmClient;
  }

  /**
   * Score faithfulness: how well the answer is grounded in the provided context.
   * @param {string} context - Retrieved context text
   * @param {string} answer - Agent's answer
   * @returns {Promise<{ score: number, explanation: string }>}
   */
  async judgeFaithfulness(context, answer) {
    const prompt = `You are an expert evaluator for RAG (Retrieval-Augmented Generation) systems.

Given the following retrieved context and an answer generated by a RAG system, evaluate how faithfully the answer is grounded in the provided context.

Context:
---
${context}
---

Answer:
---
${answer}
---

Score the faithfulness from 0.0 to 1.0, where:
- 1.0 = The answer is entirely grounded in the context with no hallucinated information
- 0.5 = The answer contains some information from the context but also includes ungrounded claims
- 0.0 = The answer completely hallucinates or contradicts the context

Respond in this exact JSON format:
{
  "score": <float between 0.0 and 1.0>,
  "explanation": "<brief explanation of your score>"
}`;

    return this._parseJudgeResponse(await this.llmClient.getResponse(prompt));
  }

  /**
   * Score relevancy: how well the answer addresses the question.
   * @param {string} question - The test question
   * @param {string} answer - Agent's answer
   * @returns {Promise<{ score: number, explanation: string }>}
   */
  async judgeRelevancy(question, answer) {
    const prompt = `You are an expert evaluator for RAG (Retrieval-Augmented Generation) systems.

Given the following question and an answer generated by a RAG system, evaluate how relevant the answer is to the question.

Question:
---
${question}
---

Answer:
---
${answer}
---

Score the relevancy from 0.0 to 1.0, where:
- 1.0 = The answer directly and comprehensively addresses the question
- 0.5 = The answer partially addresses the question but misses key aspects
- 0.0 = The answer is completely irrelevant to the question

Respond in this exact JSON format:
{
  "score": <float between 0.0 and 1.0>,
  "explanation": "<brief explanation of your score>"
}`;

    return this._parseJudgeResponse(await this.llmClient.getResponse(prompt));
  }

  /**
   * Evaluate agent trace: tool selection accuracy and reasoning coherence.
   * @param {string} question - The test question
   * @param {object[]} traceSteps - Array of tool call steps
   * @returns {Promise<{ toolSelectionAccuracy: number, reasoningCoherence: number, redundantSteps: number, explanation: string }>}
   */
  async judgeTrace(question, traceSteps) {
    const stepsStr = traceSteps.map((s, i) =>
      `Step ${i + 1}: Tool="${s.tool}", Params=${JSON.stringify(s.params)}, Duration=${s.duration_ms || 0}ms`
    ).join('\n');

    const prompt = `You are an expert evaluator for RAG Agent systems with multi-step reasoning.

Given the following question and the agent's tool call trace, evaluate:

1. Tool Selection Accuracy: Did the agent choose appropriate tools for each step? (0.0-1.0)
2. Reasoning Coherence: Does the sequence of steps make logical sense? (0.0-1.0)
3. Redundant Steps: How many steps were unnecessary or repetitive?

Question:
---
${question}
---

Agent Trace:
---
${stepsStr}
---

Respond in this exact JSON format:
{
  "toolSelectionAccuracy": <float between 0.0 and 1.0>,
  "reasoningCoherence": <float between 0.0 and 1.0>,
  "redundantSteps": <integer count>,
  "explanation": "<brief explanation>"
}`;

    const response = await this.llmClient.getResponse(prompt);
    try {
      const jsonMatch = response.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0]);
        return {
          toolSelectionAccuracy: parseFloat(parsed.toolSelectionAccuracy) || 0,
          reasoningCoherence: parseFloat(parsed.reasoningCoherence) || 0,
          redundantSteps: parseInt(parsed.redundantSteps) || 0,
          explanation: parsed.explanation || ''
        };
      }
    } catch { /* fall through */ }

    return {
      toolSelectionAccuracy: 0,
      reasoningCoherence: 0,
      redundantSteps: 0,
      explanation: `Failed to parse judge response: ${response.slice(0, 200)}`
    };
  }

  _parseJudgeResponse(response) {
    try {
      const jsonMatch = response.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0]);
        return {
          score: parseFloat(parsed.score) || 0,
          explanation: parsed.explanation || ''
        };
      }
    } catch { /* fall through */ }

    // Try to extract a number from the response
    const numberMatch = response.match(/(\d+\.?\d*)/);
    return {
      score: numberMatch ? parseFloat(numberMatch[1]) : 0,
      explanation: response.slice(0, 200)
    };
  }
}